#!/usr/bin/env python3
"""Finite archive08 metadata budget. No payload hashing or compression."""
import datetime
import json
import os
from pathlib import Path
import stat

ROOT = Path('/workspace/scratch/0669b59f9cae/DB-Exec-Parity-01')
HERE = Path(__file__).parent
groups = {}
excluded = []
all_files = set()
alias_plan = json.loads((HERE / 'alias-source-plan-01.json').read_text())
alias_destinations = {x['destination']: x for x in alias_plan['aliases']}
allowed_compiler_suffixes = {'.json', '.props', '.targets', '.rsp', '.exports',
                             '.cs', '.editorconfig', '.txt', '.dll', '.pdb'}
owned_compiler_assemblies = set()


def relative(p):
    return str(p.relative_to(ROOT))


def add(group, p):
    assert p.is_relative_to(ROOT) and not p.is_symlink(), str(p)
    s = p.lstat()
    assert stat.S_ISREG(s.st_mode), str(p)
    rel = relative(p)
    if rel in all_files:
        return
    if rel in alias_destinations:
        a = alias_destinations[rel]
        assert s.st_size == a['bytes'] and stat.S_IMODE(s.st_mode) == a['mode']
        skip(p, 'same bytes restored through explicit SHA/size/mode alias; source remains')
        return
    all_files.add(rel)
    groups.setdefault(group, []).append({'path': rel, 'bytes': s.st_size,
                                        'mode': stat.S_IMODE(s.st_mode),
                                        'mtimeNs': s.st_mtime_ns})


def skip(p, reason):
    excluded.append({'path': relative(p), 'reason': reason})


def walk(group, base, skip_dirs=(), compiler_only=False):
    assert base.is_dir(), str(base)
    for parent, dirs, files in os.walk(base, followlinks=False):
        parent = Path(parent)
        keep = []
        for n in sorted(dirs):
            p = parent / n
            assert not p.is_symlink(), str(p)
            if n in set(skip_dirs) | {'__pycache__', 'postgres-data', 'packages', 'sdk-cache'}:
                skip(p, 'rebuildable physical fixture/cache or selected compiler metadata separately; no deletion')
            else:
                keep.append(n)
        dirs[:] = keep
        for n in sorted(files):
            p = parent / n
            assert not p.is_symlink(), str(p)
            if n.endswith(('.pyc', '.sqlite', '.sqlite-wal', '.sqlite-shm', '.db', '.db-wal', '.db-shm')):
                skip(p, 'rebuildable physical database or bytecode; original remains')
            elif compiler_only and p.suffix not in allowed_compiler_suffixes:
                skip(p, 'compiler metadata selection excludes regenerable intermediates/native duplicates; publish retained')
            elif compiler_only and 'bin' in p.relative_to(ROOT).parts and p.suffix in ('.dll', '.pdb') and p.name not in owned_compiler_assemblies:
                skip(p, 'existing SDK/runtime managed copy, not a Korda project output; prior toolchain dependency, no deletion')
            else:
                add(group, p)


walk('closed-evidence08', ROOT / 'experiments/frame-pool-08')
families = ('ownership05-sqlite', 'ownership05-postgresql',
            'frame-pool08-sqlite', 'frame-pool08-postgresql')
for family in families:
    base = ROOT / 'consumers' / family / 'korda-workload'
    walk('ordinary-consumers08', base, skip_dirs=('bin', 'obj'))
    walk('ordinary-consumers08', base / 'obj', compiler_only=True)
